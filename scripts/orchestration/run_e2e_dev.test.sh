#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TEST_ROOT="$(mktemp -d)"
trap 'rm -rf "$TEST_ROOT"' EXIT
mkdir -p "$TEST_ROOT/egapro/scripts/orchestration" "$TEST_ROOT/bin"
cp "${E2E_DEV_SCRIPT_SOURCE:-$SCRIPT_DIR/run_e2e_dev.sh}" "$TEST_ROOT/egapro/scripts/orchestration/run_e2e_dev.sh"
cp "$SCRIPT_DIR/e2e_port_pool.sh" "$TEST_ROOT/egapro/scripts/orchestration/"
export TEST_ROOT
export EGAPRO_E2E_SLOT_ROOT="$TEST_ROOT/slots"
export PATH="$TEST_ROOT/bin:$PATH"

cat > "$TEST_ROOT/bin/git" <<'EOF'
#!/usr/bin/env bash
if [ "$1 $2" = "worktree add" ]; then
    mkdir -p "$4/packages/app"
elif [ "$1 $2" = "worktree remove" ]; then
    printf 'remove\n' >> "$TEST_ROOT/actions"
    rm -rf "$4"
fi
EOF
cat > "$TEST_ROOT/egapro/scripts/orchestration/log_event.sh" <<'EOF'
#!/usr/bin/env bash
printf '%s\n' "$2" >> "$TEST_ROOT/events"
EOF
cat > "$TEST_ROOT/egapro/scripts/setup-worktree.sh" <<'EOF'
#!/usr/bin/env bash
touch "$TEST_ROOT/setup_started"
while [ ! -f "$TEST_ROOT/release_setup" ]; do sleep 0.05; done
printf '# Generated by scripts/setup-worktree.sh (worktree index %s)\n' "$1" > packages/app/.env.local
EOF
cat > "$TEST_ROOT/egapro/scripts/teardown-worktree.sh" <<'EOF'
#!/usr/bin/env bash
printf 'teardown\n' >> "$TEST_ROOT/actions"
EOF
cat > "$TEST_ROOT/bin/claude" <<'EOF'
#!/usr/bin/env bash
touch "$TEST_ROOT/agent_started"
while [ ! -f "$TEST_ROOT/release_agent" ]; do sleep 0.05; done
printf '{"result":"{\\"status\\":\\"validated\\",\\"tests\\":{\\"mode\\":\\"none\\",\\"grille\\":\\"skipped\\"}}"}\n'
EOF
cat > "$TEST_ROOT/bin/lsof" <<'EOF'
#!/usr/bin/env bash
exit 1
EOF
chmod +x "$TEST_ROOT/bin/git" "$TEST_ROOT/bin/claude" "$TEST_ROOT/bin/lsof"

RUNNER="$TEST_ROOT/egapro/scripts/orchestration/run_e2e_dev.sh"
WT_PATH="$TEST_ROOT/egapro-epic123-e2e"
wait_for() {
    local file="$1" attempt
    for attempt in {1..100}; do
        [ -f "$file" ] && return 0
        sleep 0.05
    done
    echo "timed out waiting for $file" >&2
    cat "$TEST_ROOT/first.log" >&2
    return 1
}
reject_second_runner() {
    if bash "$RUNNER" 123 > "$TEST_ROOT/second.log" 2>&1; then
        echo "concurrent runner was accepted" >&2
        exit 1
    fi
    grep -q 'already running for epic 123' "$TEST_ROOT/second.log"
    [ -d "$WT_PATH" ]
    [ ! -e "$TEST_ROOT/actions" ]
}

bash "$RUNNER" 123 > "$TEST_ROOT/first.log" 2>&1 &
first_pid=$!
wait_for "$TEST_ROOT/setup_started"
reject_second_runner
touch "$TEST_ROOT/release_setup"
wait_for "$TEST_ROOT/agent_started"
reject_second_runner
touch "$TEST_ROOT/release_agent"
wait "$first_pid"
[ ! -e "$WT_PATH" ]
[ ! -e "$EGAPRO_E2E_SLOT_ROOT/epics/123" ]
[ "$(grep -c '^teardown$' "$TEST_ROOT/actions")" -eq 1 ]
[ "$(grep -c '^remove$' "$TEST_ROOT/actions")" -eq 1 ]

mkdir -p "$WT_PATH"
if bash "$RUNNER" 123 > "$TEST_ROOT/existing.log" 2>&1; then
    echo "pre-existing worktree was accepted" >&2
    exit 1
fi
grep -q 'existing E2E worktree' "$TEST_ROOT/existing.log"
[ -d "$WT_PATH" ]
[ "$(wc -l < "$TEST_ROOT/actions")" -eq 2 ]
[ ! -e "$EGAPRO_E2E_SLOT_ROOT/epics/123" ]

echo 'run_e2e_dev: PASS'
